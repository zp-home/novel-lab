# ==========================================================================
# 指标计算
# ==========================================================================

def measure(text: str) -> dict[str, float]:
    """算出契约里用到的全部指标。"""
    sents = [s for s in SENT_SPLIT.split(text) if han(s) > 0]
    lens = [han(s) for s in sents]
    n = len(lens) or 1

    rep = A.analyze(text) if han(text) >= 300 else None
    m: dict[str, float] = {}
    if rep:
        m.update({x["key"]: float(x["value"]) for x in rep["metrics"]})

    m["chars"] = han(text)
    m["avg_sent"] = sum(lens) / n
    m["short6"] = sum(1 for x in lens if x <= 6) / n
    m["long25"] = sum(1 for x in lens if x >= 25) / n
    m["sents"] = len(lens)
    m["judgment"] = len(JUDGE_RE.findall(text)) / max(han(text) / 1000.0, 0.1)
    # 代称滥用：用「少年/少女/老人/汉子」代替人名，是很重的机器味
    m["epithet"] = len(EPITHET_RE.findall(text)) / max(han(text) / 1000.0, 0.1)
    # 判断句的"起手式"是否单一。
    #
    # 这是指标反噬的典型案例：加了 judgment 下限之后，模型学会了
    # 「用 因为 开头」来刷这个指标，第 1 章里连用了三次
    # （"因为那管事背靠着宗门采买…""因为所有人越是低头…""因为脚夫们迟迟不动…"）。
    # 指标过了，读起来反而更像机器。
    # 所以再补一个反向指标：判断句不许都用同一个连词起头。
    m["because_init"] = (
        sum(1 for s in sents if s.strip()[:2] in ("因为", "所以", "因此"))
        / max(han(text) / 1000.0, 0.1))
    # 超长句占比。由独立评审（src/prose_judge.py）指出：
    # 改良版把"碎"换成了"长"——18.8% 的句子 ≥35 字，最长 60 字，
    # 而人类样本只有 7.4%。60 字一句要塞两个假设加一个推论，
    # 读者得一口气吞完。所以长句也要设上限。
    m["long35"] = sum(1 for x in lens if x >= 35) / n
    # 解释句占比：替读者把因果算清楚的那种句子。
    # 评审原文例句：「如果把灵石和账本一并交出去，林昭等于亲手放弃了
    # 老宅的地契和铁匠铺的生计，往后兄妹俩在青牛镇就彻底断了落脚的退路。」
    # —— 这是在替读者算账。判断要有，但不能每段都补一句。
    EXPO_RE = re.compile("因为|所以|要是|否则|意味着|等于|说白了|"
                         "既然|可见|也就是说|换句话说|这样一来")
    m["expo"] = (sum(1 for s in sents if EXPO_RE.search(s))
                 / max(len(sents), 1))
    return m



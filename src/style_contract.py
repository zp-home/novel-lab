HAN_RE = re.compile(r"[\u4e00-\u9fff]")
SENT_SPLIT = re.compile(r"[。！？!?…]+")

# 判断/盘算标记。用它替代「抽象词密度」。
#
# 为什么换掉：ai_flavor 的 abstract 指标数的是 命运/宿命/意义/灵魂… 这类
# 大词。那是散文的指标。小说里的「判断」完全不靠这些词，靠的是
# 因果和条件：「这镜子要是真押给了两家，那娘当年要么是被人坑了」。
# 用大词表去量小说，会得到一个永久为 0 的假指标——上一版 ch1 就是
# abstract=0.000，卡在那里把重试全浪费掉了，而文本里其实已经写了判断。
JUDGE_RE = re.compile(
    "因为|所以|要是|如果|否则|除非|与其|反倒|反正|要么|其实|"
    "怕是|怕是|值得|划不来|合算|算下来|说白了|意思是|总得|"
    "不该|本该|无非|也就是说|换句话说|等于|只能|只剩|问题是|"
    "只要|除非|免得|省得")

# 代称。中文小说里用「少年」「少女」代替人名，读者要停顿去解码，
# 是最伤可读性的机器味之一。上一版 ch1 里「少年」出现 5 次、
# 「老人」7 次、「兄长」4 次、「少女」3 次——全篇几乎不用名字。
EPITHET_RE = re.compile(
    "少年|少女|老者|老人|汉子|姑娘|丫头|小丫头|兄长|老者|那人|此人|对方")



def han(s: str) -> int:
    return len(HAN_RE.findall(s))


# ==========================================================================
# 工具：把「区间」表达成可读的目标
# ==========================================================================

def _in(v: float, lo: float | None, hi: float | None) -> bool:
    if lo is not None and v < lo:
        return False
    if hi is not None and v > hi:
        return False
    return True



def lint(text: str, profile: str = DEFAULT_PROFILE,
         seg_chars: tuple[int, int] | None = None) -> dict:
    """
    按文体档案验收。返回
        {"ok": bool, "issues": [中文], "metrics": {...}, "score": float}
    `issues` 直接可以拼进重试 prompt。
    """
    prof = PROFILES[profile]
    m = measure(text)
    hard_keys = set(prof.get("hard", []))
    issues: list[str] = []      # 硬伤：触发重写
    soft: list[str] = []        # 偏好：只进反馈，不触发重写

    if seg_chars:
        lo, hi = seg_chars
        if m["chars"] < lo:
            issues.append(f"字数 {m['chars']:.0f} 不足 {lo}，需要写满。")
        elif m["chars"] > hi:
            issues.append(f"字数 {m['chars']:.0f} 超过 {hi}，压缩环境描写。")

    for key, (lo, hi, msg) in prof["targets"].items():
        v = m.get(key)
        if v is None:
            continue
        if not _in(v, lo, hi):
            detail = (f"{msg}（当前 {key}={v:.3f}"
                      f"{'，下限 ' + str(lo) if lo is not None and v < lo else ''}"
                      f"{'，上限 ' + str(hi) if hi is not None and v > hi else ''}）")
            (issues if key in hard_keys else soft).append(detail)

    return {
        "ok": not issues,
        "issues": issues,
        "soft": soft,
        "metrics": m,
        "score": _score(m, prof),
    }


def _score(m: dict[str, float], prof: dict) -> float:
    """
    0~100，越高越贴合档案。只用于横向比较和"待修章节"排序，不做门禁。

    打分口径（改过一次）：早期版本按"离区间中点的距离"打分，
    结果一段各项都在区间内的文本只有 46 分——因为它正好在区间边缘。
    这让人误判"没写好"，其实它完全合格。

    现在改成：**落在区间内就是满分**，只有越界才按越界幅度扣分。
    这样 100 分 = 全部指标都在区间里，读起来一眼就懂。
    """
    tot = 0.0
    cnt = 0
    for key, (lo, hi, _) in prof["targets"].items():
        v = m.get(key)
        if v is None:
            continue
        cnt += 1
        if _in(v, lo, hi):
            tot += 1.0
            continue
        span = (hi - lo) if (lo is not None and hi is not None) else None
        if span is None:
            span = max(0.35 * abs(lo if lo is not None else hi), 0.02)
        dist = (lo - v) if (lo is not None and v < lo) else (v - hi)
        tot += max(0.0, 1.0 - dist / max(span, 1e-6))
    return round(100.0 * tot / max(cnt, 1), 1)


def contract(profile: str = DEFAULT_PROFILE) -> str:
    return PROFILES[profile]["contract"]


def report(text: str, profile: str = DEFAULT_PROFILE, name: str = "") -> str:
    r = lint(text, profile)
    m = r["metrics"]
    lines = [f"== {name or 'text'}  契合度 {r['score']}/100  "
             f"{'通过' if r['ok'] else '不通过'}", f"   字数 {m['chars']:.0f}"]
    for k in ("avg_sent", "short6", "long25", "long35", "sent_cv",
              "judgment", "because_init", "expo", "epithet", "concrete",
              "de", "ttr", "start_div", "g4_dup", "dialogue", "cliche",
              "emotion", "sublim"):
        if k in m:
            lines.append(f"   {k:10s} {m[k]:8.3f}")
    for i in r["issues"]:
        lines.append("   ✗ " + i)
    for i in r.get("soft", []):
        lines.append("   · " + i)
    return "\n".join(lines)


if __name__ == "__main__":
    import sys

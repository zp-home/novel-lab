"""
style_contract.py —— 文体契约（可插拔）

为什么要把「文体」单独抽成一个模块
==================================

原来的 STYLE 就写死在 write.py 的 prompt 字符串里。这带来两个问题：

1. **不可调**。用户读了前几章说「修饰过重、描述过重、读起来费劲」，
   要改就得改源码字符串，改完还只能靠肉眼判断有没有变好。
2. **不通用**。要做一个通用的长篇生成框架，文体必须是一等公民：
   不同的项目要不同的文体（网文爽文 / 悬疑冷硬 / 文学向 / 儿童向），
   而且每种文体都得有自己的量化验收标准。

所以这里做三件事：

- `PROFILES`：文体档案。每个档案 = 一段「怎么写」的自然语言契约
  + 一组「写成什么样才算合格」的量化指标区间。
- `CONTRACT` 会原样塞进 prompt。
- `lint()` 用 ai_flavor 的指标去对区间，把不合格项翻译成
  「下一轮必须改什么」的中文反馈，喂回给模型。

上一版为什么会写出「物件特写流」
================================

上一版契约里有一句「只写摄像机拍得到的：动作、器物、声音、气味、
温度、光影」，还有「不写他感到/他心想/他意识到」。
这两条合起来，等于命令模型：**只能写物体的外部特征，不许写任何
判断、概括、心理**。

模型执行得非常彻底。第 1 章 4122 字的实测：

    具象词密度  95.0 /千字   （人类参考 26）
    抽象词密度   0.0 /千字   （人类参考 4.0）
    bigram TTR   0.64        （人类参考 0.93）
    4-gram 重复  0.060       （人类参考 0.004，AI 参考 0.06）

翻译成阅读体验就是：每一个名词都要给一次特写（铜镜的漆、竹签、
灯芯的焦灰、门槛上的饼渣、鞋底在砖地上蹭出的半声闷响），
而「这件事到底要紧在哪」一句都没有。读者得自己从一堆器物里
把故事拼出来——这就是「费劲」。

而且词汇在自我复制：灯笼晃、跺脚、别过脸、嘴张了张、
笼进袖子，这些动作在两三千字里反复出现，4-gram 重复率直接
顶到 AI 参考线。

修正方向不是「少描写」，而是 **让每个细节都背功能**：
- 补回叙述者的概括与判断（抽象词回到 1~6/千字，长句回到 15%）；
- 器物细节给配额（每 300 字最多 2 处，且必须有功能）；
- 句长要真的起伏（CV ≥ 0.85），不是全靠 5 字碎句砸节奏；
- 同一动作、同一道具全章不得复用超过 2 次。

注意：这里不是要回到「AI 味」的满篇抒情。抽象词上限 6/千字、
段末升华率上限 12%，套话密度上限 4 ——依然卡得很死。
"""

